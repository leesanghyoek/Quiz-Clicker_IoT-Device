/*
 * Van Gogh style for the lake (assets/js/world.js)
 * ------------------------------------------------
 * A morning painted in the manner of "Wheat Field with Cypresses": a cobalt
 * sky with curling clouds, a chrome-yellow sun ringed with light, rolling
 * violet and green hills, a band of wheat, cypresses rising like flames.
 * Everything is laid down as short brushstrokes that follow the flow of the
 * scene, and the swirls in the sky turn slowly.
 */
(function () {
    'use strict';

    var styles = window.ARWorldStyles = window.ARWorldStyles || {};

    styles.vangogh = {
        // Across the screen (0-1) and height above the waterline (share of the sky).
        sun: [0.78, 0.55],
        // Heavier to draw than the other styles; the painting moves slowly anyway.
        frameRate: 24,
        palette: {
            uZenith: '#2a52b0',
            uHorizon: '#93c6e8',
            uSunColor: '#f6c836',
            uMist: '#5a4fa3',
            uHill: '#2f7f63',
            uField: '#d4a838',
            uLand: '#1d3f2c',
            uLake: '#2a58a8',
            uCloudLit: '#f6f1dc',
            uCloudShade: '#a7b8ea'
        },
        fragment: [
        'uniform vec3 uZenith;',
        'uniform vec3 uHorizon;',
        'uniform vec3 uSunColor;',
        'uniform vec3 uMist;',
        'uniform vec3 uHill;',
        'uniform vec3 uField;',
        'uniform vec3 uLand;',
        'uniform vec3 uLake;',
        'uniform vec3 uCloudLit;',
        'uniform vec3 uCloudShade;',
        '',
        '/* Strokes are about this wide a cell, as a share of the screen height. */',
        'const float STROKE_CELL = 0.017;',
        '',
        'vec2 sunCenter(float aspect) {',
        '    return vec2((uSun.x - 0.5) * aspect, uWater + uSun.y * 0.62);',
        '}',
        '',
        '/*',
        ' * Cypresses rising like dark flames from the shore. Returns coverage and',
        ' * whether the point is on the sunlit side of the tree.',
        ' */',
        'vec2 cypress(float x, float y, float horizon, float aspect, float aa) {',
        '    float xn = shoreX(x, aspect, 0.8);',
        '    float u = xn * 2.6;',
        '    float id = floor(u);',
        '    if (hash(vec2(id, 2.3)) < 0.35) { return vec2(0.0); }',
        '    float cx = (id + 0.3 + 0.4 * hash(vec2(id, 5.9))) / 2.6;',
        '    float height = (0.11 + 0.12 * hash(vec2(id, 7.7))) * mix(0.6, 1.0, uRelief);',
        '    float width = 0.016 + 0.01 * hash(vec2(id, 1.1));',
        '    float t = (y - horizon - 0.006) / height;',
        '    if (t < 0.0 || t > 1.0) { return vec2(0.0); }',
        '    float halfWidth = width * sin(3.1416 * pow(t, 0.55)) * (1.0 - 0.2 * t)',
        '                    + width * 0.25 * (noise(vec2(t * 9.0, id)) - 0.5);',
        '    float dx = xn - cx;',
        '    float cover = smoothstep(halfWidth + aa, halfWidth - aa, abs(dx));',
        '    return vec2(cover, step(0.0, dx * sunSide()));',
        '}',
        '',
        '/* Sky with rolling bands of cloud and a sun ringed with light. */',
        'vec3 paintedSky(vec2 a, float aspect) {',
        '    float h = max(a.y - uWater, 0.0);',
        '    float grad = pow(clamp(h / 0.8, 0.0, 1.0), 0.7);',
        '    vec3 col = mix(uHorizon, uZenith, grad);',
        '',
        '    vec2 w = vec2(a.x * 1.4 + uTime * 0.008 - uPan * PAN_STEP * 0.2, h * 3.2);',
        '    vec2 warp = vec2(fbm(w + 1.7), fbm(w + 8.3));',
        '    float swirl = fbm(w + warp * 1.8 + vec2(0.0, uTime * 0.003));',
        '    float cloud = smoothstep(0.5, 0.64, swirl) * smoothstep(0.03, 0.12, h);',
        '    col = mix(col, mix(uCloudShade, uCloudLit, smoothstep(0.55, 0.72, swirl)), cloud);',
        '',
        '    float r = length(a - sunCenter(aspect));',
        '    float rings = 0.5 + 0.5 * sin(r * 85.0 - uTime * 0.5);',
        '    float halo = smoothstep(0.2, 0.07, r);',
        '    vec3 ringCol = mix(uSunColor * vec3(1.0, 0.82, 0.45), vec3(1.0, 0.96, 0.62), rings);',
        '    col = mix(col, ringCol, halo * (0.7 + 0.25 * rings));',
        '    col = mix(col, uSunColor, smoothstep(0.058, 0.052, r));',
        '    col = mix(col, vec3(1.0, 0.98, 0.82), smoothstep(0.034, 0.028, r));',
        '    return col;',
        '}',
        '',
        '/* Hills, wheat and cypresses before any brushwork, nearest first. */',
        'vec3 paintedScene(vec2 uv, float aspect) {',
        '    float horizon = uWater;',
        '    float relief = uRelief;',
        '    float x = (uv.x - 0.5) * aspect;',
        '    float y = uv.y;',
        '    vec2 a = vec2(x, y);',
        '',
        '    if (y > horizon + max(0.27 * relief, 0.24) + 0.02) {',
        '        return paintedSky(a, aspect);',
        '    }',
        '',
        '    float aa = 1.5 / uRes.y;',
        '    vec3 col = vec3(0.0);',
        '    float alpha = 0.0;',
        '',
        '    vec2 tree = cypress(x, y, horizon, aspect, aa);',
        '    col += mix(uLand, mix(uLand, uField, 0.3), tree.y) * tree.x;',
        '    alpha += tree.x;',
        '',
        '    float ground = horizon + (0.012 + 0.008 * noise(vec2(shoreX(x, aspect, 0.8) * 4.0, 1.0))) * mix(0.6, 1.0, relief);',
        '    float wheat = smoothstep(ground + aa, ground - aa, y) * (1.0 - alpha);',
        '    col += mix(uField * 0.78, uField * 1.08, smoothstep(horizon, ground, y)) * wheat;',
        '    alpha += wheat;',
        '',
        '    if (alpha < 0.999) {',
        '        float x3 = shoreX(x, aspect, 0.55);',
        '        float top3 = horizon + (0.008 + ridge(x3 * 1.9 + 31.0, 5.3, 0.05) * 0.07) * relief;',
        '        float c3 = smoothstep(top3 + aa, top3 - aa, y) * (1.0 - alpha);',
        '        vec3 slope3 = mix(uHill, uField, 0.6);',
        '        col += mix(slope3 * 0.88, slope3 * 1.08, smoothstep(horizon, top3, y)) * c3;',
        '        alpha += c3;',
        '    }',
        '    if (alpha < 0.999) {',
        '        float x2 = shoreX(x, aspect, 0.36);',
        '        float top2 = horizon + (0.012 + ridge(x2 * 1.3 + 11.0, 7.3, 0.1) * 0.13) * relief;',
        '        float c2 = smoothstep(top2 + aa, top2 - aa, y) * (1.0 - alpha);',
        '        col += mix(uHill * 0.86, uHill * 1.1, smoothstep(horizon, top2, y)) * c2;',
        '        alpha += c2;',
        '    }',
        '    if (alpha < 0.999) {',
        '        float x1 = shoreX(x, aspect, 0.2);',
        '        float top1 = horizon + (0.02 + ridge(x1 * 0.9 + 3.0, 2.1, 0.2) * 0.22) * relief;',
        '        float c1 = smoothstep(top1 + aa, top1 - aa, y) * (1.0 - alpha);',
        '        col += mix(uMist * 0.9, mix(uMist, uHorizon, 0.25), smoothstep(horizon, top1, y)) * c1;',
        '        alpha += c1;',
        '    }',
        '    if (alpha < 0.999) {',
        '        col += paintedSky(a, aspect) * (1.0 - alpha);',
        '    }',
        '    return col;',
        '}',
        '',
        '/* What the canvas shows at uv before brushwork: land and sky, or the lake mirroring them. */',
        'vec3 surfaceColor(vec2 uv, float aspect) {',
        '    float horizon = uWater;',
        '    if (uv.y >= horizon) {',
        '        return paintedScene(uv, aspect);',
        '    }',
        '    float depth = horizon - uv.y;',
        '    vec3 reflection = paintedScene(vec2(uv.x, horizon + depth * 1.05), aspect);',
        '    float fresnel = smoothstep(0.0, 0.4, depth);',
        '    vec3 col = mix(reflection, uLake, 0.3 + fresnel * 0.45);',
        '    float column = exp(-abs((uv.x - uSun.x) * aspect) * (7.0 + depth * 9.0));',
        '    float broken = step(0.45, hash(vec2(floor(depth * 90.0), 3.0)));',
        '    return mix(col, uSunColor, column * 0.6 * broken);',
        '}',
        '',
        '/*',
        ' * Direction the brush travels at a (x in aspect units, y as on screen):',
        ' * level across the water, up through the cypresses, rolling over the hills,',
        ' * curling around slow vortices in the sky and circling the sun.',
        ' */',
        'vec2 flowAt(vec2 a, float aspect) {',
        '    float horizon = uWater;',
        '    float h = a.y - horizon;',
        '    if (h < 0.0) {',
        '        return vec2(1.0, 0.06 * sin(a.x * 16.0 + h * 50.0));',
        '    }',
        '    if (cypress(a.x, a.y, horizon, aspect, 0.002).x > 0.5) {',
        '        return vec2(0.25 * sin(h * 60.0 + a.x * 30.0), 1.0);',
        '    }',
        '    vec2 v = vec2(1.0, 0.4 * sin(a.x * 4.5 + h * 10.0 + uTime * 0.04));',
        '    if (h > 0.1) {',
        '        for (int k = 0; k < 3; k++) {',
        '            float fk = float(k);',
        '            vec2 c = vec2(',
        '                (fk * 0.62 - 0.55) * aspect * 0.8 + sin(uTime * 0.01 + fk) * 0.04 - uPan * aspect * PAN_STEP * 0.15,',
        '                horizon + 0.3 + 0.1 * sin(fk * 2.3)',
        '            );',
        '            vec2 d = a - c;',
        '            float r = length(d) + 0.001;',
        '            v += vec2(-d.y, d.x) / r * exp(-r * 7.0) * 2.2;',
        '        }',
        '    }',
        '    vec2 s = a - sunCenter(aspect);',
        '    float rs = length(s) + 0.001;',
        '    return mix(v, vec2(-s.y, s.x) / rs, smoothstep(0.26, 0.1, rs));',
        '}',
        '',
        '/*',
        ' * Brushwork: the canvas is covered in short strokes laid on a jittered grid.',
        ' * Each stroke takes one colour from the scene at its centre, follows the',
        ' * flow, and shows bristle marks and a raised edge of paint.',
        ' */',
        'vec3 brushwork(vec2 uv, float aspect) {',
        '    float horizon = uWater;',
        '    vec2 shift = vec2(uPan * aspect * PAN_STEP * 0.4, -horizon);',
        '    vec2 a = vec2((uv.x - 0.5) * aspect, uv.y);',
        '    vec2 q = a + shift;',
        '    vec2 cell = floor(q / STROKE_CELL);',
        '',
        '    float best = -1.0;',
        '    vec2 winner = vec2(0.0);',
        '    float tint = 0.0;',
        '    float across = 0.0;',
        '    float along = 0.0;',
        '',
        '    for (int j = -1; j <= 1; j++) {',
        '        for (int i = -1; i <= 1; i++) {',
        '            vec2 id = cell + vec2(float(i), float(j));',
        '            float r1 = hash(id);',
        '            float r2 = hash(id + 17.3);',
        '            vec2 c = (id + 0.5 + (vec2(r1, r2) - 0.5) * 0.9) * STROKE_CELL;',
        '            vec2 dir = normalize(flowAt(c - shift, aspect));',
        '            vec2 rel = q - c;',
        '            float al = dot(rel, dir) / (STROKE_CELL * (1.0 + 0.7 * r1));',
        '            float ac = dot(rel, vec2(-dir.y, dir.x)) / (STROKE_CELL * (0.32 + 0.14 * r2));',
        '            if (al * al + ac * ac < 1.0) {',
        '                float z = hash(id + 5.1);',
        '                if (z > best) {',
        '                    best = z;',
        '                    winner = c - shift;',
        '                    tint = hash(id + 9.7) - 0.5;',
        '                    across = ac;',
        '                    along = al;',
        '                }',
        '            }',
        '        }',
        '    }',
        '',
        '    if (best < 0.0) {',
        '        /* A gap between strokes shows the darker underpainting. */',
        '        return surfaceColor(uv, aspect) * 0.78;',
        '    }',
        '',
        '    vec2 centreUv = vec2(winner.x / aspect + 0.5, winner.y);',
        '    vec3 col = surfaceColor(centreUv, aspect);',
        '    col = mix(col, floor(col * 7.0 + 0.5) / 7.0, 0.35);',
        '    col *= 0.88 + 0.28 * (tint + 0.5);',
        '    col += vec3(0.05, 0.02, -0.04) * tint * 2.0;',
        '    col *= 1.0 + sin(across * 9.0 + tint * 20.0) * 0.05;',
        '    col *= 1.0 - smoothstep(0.6, 1.0, abs(across)) * 0.16 - smoothstep(0.75, 1.0, abs(along)) * 0.08;',
        '    col *= 1.0 - across * 0.06;',
        '    return col;',
        '}',
        '',
        'void main() {',
        '    vec2 uv = gl_FragCoord.xy / uRes;',
        '    float aspect = uRes.x / uRes.y;',
        '    vec3 col = brushwork(uv, aspect);',
        '',
        '    if (uv.y >= uWater) {',
        '        col = mix(col, uLand * 0.45, birds(uv, aspect));',
        '    } else if (uLanternCount > 0.5) {',
        '        col = lanterns(col, uv, aspect, uWater, 0.0);',
        '    }',
        '',
        '    vec2 v = uv - 0.5;',
        '    col *= 1.0 - dot(v, v) * 0.22;',
        '    gl_FragColor = vec4(col, 1.0);',
        '}'
    ].join('\n')
    };
})();
