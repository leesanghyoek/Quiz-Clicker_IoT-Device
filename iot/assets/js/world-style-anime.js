/*
 * Anime style for the lake (assets/js/world.js)
 * ---------------------------------------------
 * The flat, crisp look of an anime background: a bright morning, towering
 * cel-shaded clouds, hills with sunlit and shaded faces, two-tone pines on
 * the shore, and clear blue water streaked with strokes of light.
 */
(function () {
    'use strict';

    var styles = window.ARWorldStyles = window.ARWorldStyles || {};

    styles.anime = {
        // Across the screen (0-1) and height above the waterline (share of the sky).
        sun: [0.8, 0.52],
        frameRate: 30,
        palette: {
            uZenith: '#1262d6',
            uHorizon: '#bdf3ff',
            uMist: '#a3dbe9',
            uSunColor: '#fff3d1',
            uLand: '#0d5a49',
            uLake: '#1a78c2',
            uCloudLit: '#ffffff',
            uCloudMid: '#dcecfb',
            uCloudShade: '#9fbfeb'
        },
        fragment: [
        'uniform vec3 uZenith;',
        'uniform vec3 uHorizon;',
        'uniform vec3 uMist;',
        'uniform vec3 uSunColor;',
        'uniform vec3 uLand;',
        'uniform vec3 uLake;',
        'uniform vec3 uCloudLit;',
        'uniform vec3 uCloudMid;',
        'uniform vec3 uCloudShade;',
        '',
        '/* The broad shape of a ridge only, for deciding which faces meet the sun. */',
        'float ridgeBroad(float x, float seed, float sharp) {',
        '    float v = 0.0;',
        '    float a = 0.5;',
        '    float f = 1.0;',
        '    for (int i = 0; i < 2; i++) {',
        '        float n = noise(vec2(x * f + seed, seed * 1.7));',
        '        n = mix(n, 1.0 - abs(n * 2.0 - 1.0), sharp);',
        '        v += a * n;',
        '        f *= 2.05;',
        '        a *= 0.47;',
        '    }',
        '    return v;',
        '}',
        '/*',
        ' * Cumulus in clusters, with nearly flat bases and towering tops. c.x runs',
        ' * across the sky, c.y is the height above the cloud base.',
        ' */',
        'float cumulus(vec2 c, float seed) {',
        '    float towers = noise(vec2(c.x * 0.9 + seed, seed));',
        '    float presence = smoothstep(0.38, 0.78, towers);',
        '    float body = fbm(vec2(c.x * 2.2, c.y * 3.4) + seed * 3.1);',
        '    float d = body + presence * 0.95 - 0.45 - c.y * (2.6 - presence * 1.4);',
        '    float base = c.y + (noise(vec2(c.x * 3.0, seed * 2.0)) - 0.5) * 0.05;',
        '    return d - smoothstep(0.0, -0.03, base) * 2.0;',
        '}',
        '',
        '/* One cloud bank drawn in flat cel tones with a crisp outline. */',
        'vec3 cloudBank(vec3 col, vec2 p, float aspect, float baseY, float scale, float seed, float aa) {',
        '    float wind = uTime * 0.006 + uPan * PAN_STEP * 0.12;',
        '    vec2 c = vec2(((p.x - 0.5) * aspect) / scale + wind, (p.y - baseY) / scale);',
        '    if (c.y < -0.06 || c.y > 0.8) { return col; }',
        '    float d = cumulus(c, seed);',
        '    float edge = 0.62;',
        '    float cover = smoothstep(edge - aa, edge + aa, d);',
        '    if (cover <= 0.0) { return col; }',
        '',
        '    /* Toward the sun is up and to its side; denser there means we are in shade. */',
        '    vec2 toLight = vec2(sunSide() * 0.03, 0.045);',
        '    float occlusion = cumulus(c + toLight, seed) - d;',
        '    float shade = smoothstep(-0.02, 0.0, occlusion);',
        '    float deep = smoothstep(0.1, 0.12, occlusion);',
        '    vec3 tone = mix(uCloudLit, uCloudMid, shade);',
        '    tone = mix(tone, uCloudShade, deep);',
        '    /* Flat undersides pick up the blue of the sky below. */',
        '    tone = mix(tone, uCloudShade * 0.95, smoothstep(0.05, 0.0, c.y) * 0.7);',
        '    /* A bright rim where the lit edge meets the sky. */',
        '    float rim = smoothstep(edge + 0.05, edge, d) * (1.0 - shade);',
        '    tone = mix(tone, vec3(1.0), rim * 0.8);',
        '    return mix(col, tone, cover);',
        '}',
        '',
        'vec3 skyColor(vec2 p, float aspect) {',
        '    float horizon = uWater;',
        '    float h = max(p.y - horizon, 0.0);',
        '    float aa = 2.0 / uRes.y;',
        '    float grad = pow(clamp(h / 0.75, 0.0, 1.0), 0.75);',
        '    vec3 col = mix(uHorizon, uZenith, grad);',
        '',
        '    /* Sun: a crisp disc in a wide bloom. */',
        '    vec2 sunPos = vec2((uSun.x - 0.5) * aspect, horizon + uSun.y * 0.62);',
        '    vec2 sp = vec2((p.x - 0.5) * aspect, p.y) - sunPos;',
        '    float sunDist = length(sp);',
        '    col += uSunColor * (0.4 * exp(-sunDist * 3.2) + 0.35 * exp(-sunDist * 16.0));',
        '',
        '    col = mix(col, vec3(1.0), smoothstep(0.034, 0.034 - aa, sunDist));',
        '',
        '    /* High small puffs, then the big bank of towers above the hills. */',
        '    col = cloudBank(col, p, aspect, horizon + 0.5, 0.11, 4.0, 0.03);',
        '    col = cloudBank(col, p, aspect, horizon + 0.13, 0.34, 1.0, 0.015);',
        '    return col;',
        '}',
        '',
        '/*',
        ' * One range of hills in two flat tones: faces turned to the sun are lit,',
        ' * the others fall into a cool shadow. Mist pools at the foot of each range.',
        ' */',
        'void addRange(inout vec3 col, inout float alpha, float y, float x, float top, float broadSeed,',
        '              float freq, float sharp, float offset, float depthTone, float horizon, float aa) {',
        '    float cover = smoothstep(top + aa, top - aa, y) * (1.0 - alpha);',
        '    if (cover <= 0.0) { return; }',
        '',
        '    /* Lean the light/shade split with height so faces look slanted. */',
        '    float xs = (x + (top - y) * 0.7 * sunSide()) * freq + offset;',
        '    float slope = ridgeBroad(xs + 0.02, broadSeed, sharp) - ridgeBroad(xs - 0.02, broadSeed, sharp);',
        '    float lit = smoothstep(0.0003, -0.0003, slope * sunSide());',
        '',
        '    vec3 base = mix(uMist, uLand, depthTone);',
        '    vec3 shadow = mix(base, uZenith * 0.5, 0.18) * 0.9;',
        '    vec3 light = mix(base, uSunColor, 0.16 + 0.12 * (1.0 - depthTone));',
        '    vec3 c = mix(shadow, light, lit);',
        '',
        '    float h01 = clamp((y - horizon) / max(top - horizon, 0.002), 0.0, 1.0);',
        '    c = mix(c, uMist, (1.0 - h01) * (1.0 - h01) * 0.55 * (1.0 - depthTone * 0.5));',
        '',
        '    col += c * cover;',
        '    alpha += cover;',
        '}',
        '',
        '/* Landscape colour (premultiplied) and coverage at p; sky shows where alpha < 1. */',
        'vec4 landscape(vec2 p, float aspect, float horizon) {',
        '    float relief = uRelief;',
        '    float y = p.y;',
        '',
        '    if (y > horizon + 0.34 * relief + 0.01) {',
        '        return vec4(0.0);',
        '    }',
        '',
        '    float x = (p.x - 0.5) * aspect;',
        '    float aa = 1.2 / uRes.y;',
        '    vec3 col = vec3(0.0);',
        '    float alpha = 0.0;',
        '',
        '    /* Shore: pines in two tones, the half facing the sun lighter. */',
        '    float xn = shoreX(x, aspect, 0.85);',
        '    float ground = horizon + 0.003 + 0.01 * noise(vec2(xn * 3.0, 2.0)) * relief;',
        '    float u1 = xn * 46.0;',
        '    float f1 = fract(u1) - 0.5;',
        '    float tree1 = (0.012 + 0.03 * hash(vec2(floor(u1), 3.1))) * (1.0 - abs(f1) * 2.0);',
        '    float u2 = u1 + 0.5;',
        '    float f2 = fract(u2) - 0.5;',
        '    float tree2 = (0.008 + 0.022 * hash(vec2(floor(u2), 8.7))) * (1.0 - abs(f2) * 2.0);',
        '    float front = step(tree1, tree2);',
        '    float pines = ground + max(tree1, tree2) * mix(0.55, 1.0, relief);',
        '    float shoreCover = smoothstep(pines + aa, pines - aa, y);',
        '    float sunny = step(0.0, mix(f1, f2, front) * sunSide()) * step(ground + 0.002, y);',
        '    vec3 pine = mix(uLand * 0.9, mix(uLand, uSunColor, 0.22), sunny);',
        '    col += pine * shoreCover;',
        '    alpha += shoreCover;',
        '',
        '    if (alpha < 0.999) {',
        '        float x3 = shoreX(x, aspect, 0.55);',
        '        float top3 = horizon + (0.006 + ridge(x3 * 2.6 + 31.0, 5.3, 0.25) * 0.085) * relief;',
        '        addRange(col, alpha, y, x3, top3, 5.3, 2.6, 0.25, 31.0, 0.8, horizon, aa);',
        '    }',
        '    if (alpha < 0.999) {',
        '        float x2 = shoreX(x, aspect, 0.36);',
        '        float top2 = horizon + (0.01 + ridge(x2 * 1.7 + 11.0, 7.3, 0.45) * 0.14) * relief;',
        '        addRange(col, alpha, y, x2, top2, 7.3, 1.7, 0.45, 11.0, 0.6, horizon, aa);',
        '    }',
        '    if (alpha < 0.999) {',
        '        float x1 = shoreX(x, aspect, 0.22);',
        '        float top1 = horizon + (0.015 + ridge(x1 * 1.15 + 3.0, 2.1, 0.65) * 0.21) * relief;',
        '        addRange(col, alpha, y, x1, top1, 2.1, 1.15, 0.65, 3.0, 0.42, horizon, aa);',
        '    }',
        '    if (alpha < 0.999) {',
        '        float x0 = shoreX(x, aspect, 0.12);',
        '        float top0 = horizon + (0.02 + ridge(x0 * 0.8, 3.1, 0.85) * 0.3) * relief;',
        '        addRange(col, alpha, y, x0, top0, 3.1, 0.8, 0.85, 0.0, 0.24, horizon, aa);',
        '    }',
        '',
        '    return vec4(col, alpha);',
        '}',
        '',
        'vec3 scene(vec2 p, float aspect) {',
        '    vec4 land = landscape(p, aspect, uWater);',
        '',
        '    if (land.a > 0.999) {',
        '        return land.rgb;',
        '    }',
        '',
        '    return land.rgb + skyColor(p, aspect) * (1.0 - land.a);',
        '}',
        '',
        'void main() {',
        '    vec2 uv = gl_FragCoord.xy / uRes;',
        '    float aspect = uRes.x / uRes.y;',
        '    float horizon = uWater;',
        '    vec3 col;',
        '',
        '    if (uv.y >= horizon) {',
        '        col = scene(uv, aspect);',
        '        col = mix(col, uLand * 0.8, birds(uv, aspect));',
        '    } else {',
        '        /*',
        '         * Lake: a mirror broken into thin horizontal bands, laid over clear',
        '         * blue water, with crisp strokes of light that thicken toward the sun.',
        '         */',
        '        float depth = horizon - uv.y;',
        '        float gx = (uv.x - 0.5) * aspect + uPan * aspect * PAN_STEP;',
        '        float rows = 7.0 / (depth + 0.03);',
        '        float row = floor(rows);',
        '        float rowF = fract(rows);',
        '        float sway = (hash(vec2(row, 1.0)) - 0.5) * 0.012 * smoothstep(0.0, 0.05, depth)',
        '                   + sin(uTime * 0.6 + row * 1.7) * 0.002;',
        '        vec2 mirrored = vec2(uv.x + sway, horizon + depth);',
        '        vec3 reflection = scene(mirrored, aspect);',
        '        float fresnel = smoothstep(0.0, 0.45, depth);',
        '        col = mix(reflection, uLake, 0.22 + fresnel * 0.5);',
        '        col = mix(col, uLake * 0.82, smoothstep(0.15, 0.6, depth) * 0.35);',
        '',
        '        float column = exp(-abs((uv.x - uSun.x) * aspect) * (6.0 + depth * 10.0));',
        '        float line = smoothstep(0.0, 0.06, rowF) * smoothstep(0.32, 0.22, rowF)',
        '                   * smoothstep(0.015, 0.05, depth);',
        '        float drift = uTime * 0.05 * (hash(vec2(row, 7.0)) - 0.5);',
        '        float seg = floor((gx + drift) * (5.0 + hash(vec2(row, 3.0)) * 6.0) * (1.0 + depth * 2.0));',
        '        float twinkle = step(0.35, hash(vec2(seg, floor(uTime * 1.5 + row))));',
        '        float dash = step(0.9 - column * 0.45, hash(vec2(seg, row))) * twinkle;',
        '        col = mix(col, vec3(1.0, 0.99, 0.94), dash * line * (0.55 + column * 0.45));',
        '        col += uSunColor * column * 0.12;',
        '',
        '        col = mix(col, vec3(1.0), smoothstep(0.0025, 0.0, depth) * 0.5);',
        '',
        '        if (uLanternCount > 0.5) {',
        '            col = lanterns(col, uv, aspect, horizon, sway * 40.0);',
        '        }',
        '    }',
        '',
        '    /* A light vignette and dithering against banding in the gradients. */',
        '    vec2 v = uv - 0.5;',
        '    col *= 1.0 - dot(v, v) * 0.16;',
        '    col += (hash(gl_FragCoord.xy + fract(uTime)) - 0.5) / 255.0;',
        '    gl_FragColor = vec4(col, 1.0);',
        '}'
    ].join('\n')
    };
})();
